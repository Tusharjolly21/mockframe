import { mkdirSync, writeFileSync } from "node:fs";
import { icons as solar } from "@iconify-json/solar";

const suffix = "-bold-duotone";
const required = [
  "star", "heart", "fire", "rocket", "rocket-2", "bolt", "crown", "crown-star", "widget-2", "cup-star", "medal-ribbons-star",
  "check-circle", "close-circle", "danger-triangle", "question-circle", "info-circle", "bell",
  "arrow-right", "arrow-left", "arrow-up", "arrow-down", "undo-left-round", "cursor",
  "smartphone", "laptop", "monitor", "camera", "gallery", "music-note-2", "videocamera-record",
  "chat-round-dots", "letter", "phone-calling", "user-circle", "users-group-rounded",
  "magnifer", "settings", "lock-keyhole", "shield-check", "eye", "link-round", "refresh-circle",
  "magic-stick-3", "key", "export", "cart-large-2", "bag-smile", "wallet-money", "dollar", "tag-price", "gift",
  "calendar", "clock-circle", "map-point", "planet", "planet-2", "planet-3", "planet-4", "earth",
  "cloud", "cloud-sun", "cloud-rain", "moon-stars", "moon", "sun", "sun-2", "leaf", "water", "waterdrop",
  "wind", "snowflake", "cat", "paw", "bug", "bug-minimalistic", "satellite", "ufo", "atom", "star-fall",
];

// Keep a generous but intentional catalog. Shipping all 7,400 Solar glyphs added
// more than 6 MB of raw JavaScript to every editor visit.
const topicWords = [
  "arrow", "planet", "earth", "moon", "sun", "star", "cloud", "leaf", "tree", "flower", "water", "wind",
  "snow", "fire", "animal", "cat", "dog", "paw", "bug", "fish", "bird", "rocket", "satellite", "map",
  "camera", "gallery", "phone", "laptop", "monitor", "chat", "letter", "user", "heart", "check", "danger",
  "info", "question", "bell", "shield", "lock", "eye", "link", "cart", "bag", "wallet", "gift", "calendar",
  "clock", "music", "video", "play", "spark", "magic", "crown", "cup", "medal", "flag", "pin", "cursor",
];

const available = Object.keys(solar.icons)
  .filter((name) => name.endsWith(suffix))
  .map((name) => name.slice(0, -suffix.length));
const selected = new Set(required.filter((name) => solar.icons[name + suffix]));

for (const word of topicWords) {
  for (const name of available.filter((candidate) => candidate.includes(word)).slice(0, 8)) selected.add(name);
}

const ordered = [...selected].sort((a, b) => {
  const ai = required.indexOf(a);
  const bi = required.indexOf(b);
  if (ai >= 0 || bi >= 0) return (ai < 0 ? Number.MAX_SAFE_INTEGER : ai) - (bi < 0 ? Number.MAX_SAFE_INTEGER : bi);
  return a.localeCompare(b);
});

const bodies = Object.fromEntries(ordered.map((name) => [name, solar.icons[name + suffix].body]));
const source = `/* Generated by scripts/generate-icon-catalog.mjs. Do not edit manually. */\n` +
  `export const SOLAR_ICON_BODIES: Record<string, string> = ${JSON.stringify(bodies)};\n`;

mkdirSync(new URL("../apps/web/lib/generated/", import.meta.url), { recursive: true });
writeFileSync(new URL("../apps/web/lib/generated/solarIconBodies.ts", import.meta.url), source);
console.log(`Generated ${ordered.length} curated Solar icons.`);
