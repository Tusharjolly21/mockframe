/**
 * Compiles registry/<id>/{device.json, frame-*.svg} into src/generated/registry.ts
 * so the renderer can consume devices with zero fetches in any environment.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const PKG = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = path.join(PKG, "registry");
const OUT = path.join(PKG, "src", "generated");

const section = (svg, name) => {
  const m = svg.match(new RegExp(`<!--${name}-->([\\s\\S]*?)<!--/${name}-->`));
  if (!m) throw new Error(`marker ${name} missing`);
  return m[1].trim();
};

const devices = [];
for (const id of fs.readdirSync(ROOT).sort()) {
  const dir = path.join(ROOT, id);
  if (!fs.statSync(dir).isDirectory()) continue;
  const meta = JSON.parse(fs.readFileSync(path.join(dir, "device.json"), "utf8"));
  const variants = meta.variants.map((v) => {
    const svg = fs.readFileSync(path.join(dir, v.svg), "utf8");
    return {
      id: v.id,
      label: v.label,
      body: section(svg, "BODY"),
      overlay: section(svg, "OVERLAY"),
      preview: svg, // full standalone svg (with screen placeholder) for pickers
    };
  });
  devices.push({ ...meta, variants });
  console.log(`registry: ${id} (${variants.length} variants)`);
}

fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(
  path.join(OUT, "registry.ts"),
  `/* AUTO-GENERATED by scripts/build-registry.mjs — do not edit by hand. */
import type { Device } from "../types";

export const DEVICES: Device[] = ${JSON.stringify(devices, null, 1)};
`
);
console.log(`wrote src/generated/registry.ts (${devices.length} devices)`);
